def load_and_interpolate_sov_data(file_paths: list[str], scale_factor: float = 0.75) -> dict:
    """
    Ingests raw .mat files for the Service Operation Vessel (SOV), combines them,
    sums the active generator powers, scales by scale_factor, and interpolates onto a 1 Hz grid.
    Defensively unpacks cell-wrapped arrays generated by matio table mapping.
    """
    t_c = []
    Pd_c = []
    t0_offset = 0.0
    
    generator_columns = [
        'DG1_GeneratorActivePower',
        'DG2_GeneratorActivePower',
        'DG3_GeneratorActivePower',
        'DG4_GeneratorActivePower'
    ]
    
    for path in file_paths:
        if not os.path.exists(path):
            raise FileNotFoundError(f"Vessel data file not found at: {path}")
            
        mat_contents = load_from_mat(path, raw_data=False)
        raw_data = mat_contents['SOV_data']  
        
        def _clean_string(x) -> str:
            if isinstance(x, np.ndarray):
                x = x.item() if x.size == 1 else x.flatten()[0]
            if isinstance(x, bytes):
                return x.decode('utf-8').strip()
            return str(x).strip()

        def _clean_float(x) -> float:
            if isinstance(x, np.ndarray):
                return float(x.item() if x.size == 1 else x.flatten()[0])
            return float(x)
        
        timestamps = [_clean_string(val) for val in raw_data['Timestamp_UTC_']]
        dates = pd.to_datetime(timestamps, format='mixed')
        elapsed_seconds = (dates - dates[0]).total_seconds().to_numpy()
        
        power_matrix = np.zeros((len(dates), len(generator_columns)))
        for col_idx, col in enumerate(generator_columns):
            power_matrix[:, col_idx] = [_clean_float(val) for val in raw_data[col]]
            
        # --- SCALE DEMAND PROFILE HERE ---
        power_demand = np.sum(power_matrix, axis=1) * scale_factor
        
        t_target = np.arange(0, int(elapsed_seconds[-1]) + 1, dtype=np.float64)
        power_interp = np.interp(t_target, elapsed_seconds, power_demand)
        
        t_c.append(t_target + t0_offset)
        Pd_c.append(power_interp)
        t0_offset = t_c[-1][-1]
        
    return {
        't': np.concatenate(t_c),
        'Pd': np.concatenate(Pd_c)
    }


def load_and_cache_entire_fleet(config: EnvConfig) -> dict[int, dict]:
    """
    Executes disk I/O to cache all available days (1-14) in RAM.
    Uses a compressed binary .npz file tagged with the scale factor.
    """
    # 1. Fetch scale factor from EnvConfig or default to 0.75
    scale_factor = getattr(config, 'power_scale_factor', 0.75)
    
    # Tag cache path with scale factor so changed scales force re-parsing
    cache_filename = f"fleet_data_cache_scale_{scale_factor:.2f}.npz"
    cache_path = os.path.join(config.cache_dir, cache_filename)
    
    # --- STAGE 1: Try to load from the binary cache ---
    if os.path.exists(cache_path):
        print(f"Loading fleet data from binary cache ({cache_filename})...")
        start_t = time.perf_counter()
        fleet_cache = {}
        
        with np.load(cache_path) as data:
            for file_key in data.files:
                parts = file_key.split('_')
                day_num = int(parts[1])
                var_name = parts[2]  # 't' or 'Pd'
                
                if day_num not in fleet_cache:
                    fleet_cache[day_num] = {}
                fleet_cache[day_num][var_name] = data[file_key]
                
        print(f" -> Cache instantly loaded in {time.perf_counter() - start_t:.3f} seconds.")
        return fleet_cache

    # --- STAGE 2: If no cache exists, parse raw .mat files ---
    fleet_cache = {}
    dir_path = config.data_dir
    all_fleet_files = [f"{dir_path}/SOV_{day:02d}-Feb-2023.mat" for day in range(1, 15)]
    
    print(f"Binary cache not found. Parsing raw .mat files with scale_factor={scale_factor}...")
    for idx, path in enumerate(all_fleet_files):
        day_num = idx + 1
        if os.path.exists(path):
            fleet_cache[day_num] = load_and_interpolate_sov_data([path], scale_factor=scale_factor)
            print(f" -> Day {day_num:02d} successfully parsed and scaled.")
        else:
            # Fallback mock data with scaling
            print(f" [!] File not found at {path}. Generating fallback numerical profile for Day {day_num:02d}...")
            t_mock = np.arange(0, 86400, dtype=np.float64)
            pd_mock = (600.0 + 200.0 * np.sin(2 * np.pi * t_mock / 86400) + np.random.normal(0, 30, len(t_mock))) * scale_factor
            fleet_cache[day_num] = {'t': t_mock, 'Pd': pd_mock}
            
    # --- STAGE 3: Save to binary cache ---
    print(f"Compressing and writing data to {cache_filename}...")
    save_dict = {}
    for day_num, data_dict in fleet_cache.items():
        save_dict[f"day_{day_num}_t"] = data_dict['t']
        save_dict[f"day_{day_num}_Pd"] = data_dict['Pd']

    cache_dir = os.path.dirname(cache_path)
    os.makedirs(cache_dir, exist_ok=True)
        
    np.savez_compressed(cache_path, **save_dict)
    print("All operational days scaled, cached in RAM, and written to disk.")
    
    return fleet_cache


def calibrate_markov_chain(data_dict: dict, config: SimConfig, manual_edges=None) -> dict:
    """Standard orchestration routine for single continuous data sets."""
    ds_data = downsample_block_mean(data_dict['t'], data_dict['Pd'], config.delta_t, align='t0')
    mc_model = fit_dtmc(ds_data['Pd'], config.N_pd, config.alpha_mc, manual_edges=manual_edges)
    mc_model['Delta'] = config.delta_t  
    return mc_model

